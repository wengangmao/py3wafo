"""Installation discovery adapted from MATLAB's root-level path utilities.

Python packages use normal imports rather than adding every subdirectory to
the global module search path. These helpers inspect the installed package.
"""
from pathlib import Path as _Path
import os as _os
from ..onedim import parzen


def waforoot():
    """Return the absolute installed wafo package directory as a string."""
    return str(_Path(__file__).resolve().parents[1])


def wafopath(part='tools', add=None, first=None):
    """Return installed namespace paths without changing sys.path.

    part accepts tools/docs/wdemos/data/papers. Explicit MATLAB search-path
    mutation arguments are rejected: install/import py3wafo instead.
    """
    if add is not None or first is not None:
        raise ValueError('Python imports need no MATLAB search-path mutation; install py3wafo and import its namespaces')
    base = _Path(waforoot())
    if part == 'tools':
        excluded = {'docs', 'wdemos', 'data', 'papers', 'source', 'root'}
        return [str(p) for p in sorted(base.iterdir()) if p.is_dir() and not p.name.startswith('_') and p.name not in excluded and (p/'__init__.py').is_file()]
    if part not in ('docs', 'wdemos', 'data', 'papers'):
        raise ValueError('Unknown WAFO path category')
    directory = base/part
    result = [str(directory)]
    if part == 'papers':
        result.extend(str(p) for p in sorted(directory.iterdir()) if p.is_dir() and not p.name.startswith('_'))
    return result


def wafoexepath():
    """Return the portable Python driver namespace, including a separator.

    The replacement contains Python modules, not platform-specific binaries.
    Invoke the safe driver with python -m py3wafo or wafo.exec.run_driver.
    """
    return str(_Path(waforoot())/'exec')+_os.sep


def pathdef():
    """Return installed WAFO namespace paths separated by os.pathsep.

    The source file is an autogenerated snapshot of one MATLAB installation;
    this replacement reports the current package rather than stale D: paths.
    """
    return _os.pathsep.join([waforoot()]+wafopath()+sum((wafopath(part) for part in ('docs', 'wdemos', 'data', 'papers')), []))


def initwafo(opt='normal', add=None, first=None):
    """Discover installed namespaces for minimum/normal/full initialization.

    Return a mapping containing version, root and paths. Installation already
    initializes imports; this function makes no process-wide path changes.
    """
    from .. import __version__
    if opt not in ('minimum', 'normal', 'full'):
        raise ValueError('opt must be minimum, normal, or full')
    paths = [waforoot()]+wafopath('tools', add, first)
    if opt in ('normal', 'full'):
        paths += sum((wafopath(part) for part in ('docs', 'wdemos', 'data')), [])
    if opt == 'full':
        paths += wafopath('papers')
    return {'root': waforoot(), 'version': __version__, 'paths': paths}


__all__ = ['initwafo', 'waforoot', 'wafopath', 'wafoexepath', 'pathdef', 'parzen']
